export async function getLang() {
  const store = await cookies();
  return store.get("fiba_lang")?.value === "tr" ? "tr" : "en";
}

export async function getT() {
  const lang = await getLang();
  const d = DICT[lang];
  return { lang, t: (key) => d[key] ?? DICT.tr[key] ?? key, locale: lang === "en" ? "en-GB" : "tr-TR" };
}

// Oyuncu ekranlarında turnuva adı dile göre üretilir (DB'deki ad Türkçedir)
export function tournamentTitle(t, lang, game, size) {
  return `Fiba Games ${t(game)} — ${size} ${t("players")}`;
}

export function roundLabel(t, roundIdx, totalRounds) {
  const remaining = totalRounds - roundIdx;
  if (remaining === 1) return t("final");
  if (remaining === 2) return t("semiFinal");
  if (remaining === 3) return t("quarterFinal");
  return `${t("round")} ${roundIdx + 1}`;
}
